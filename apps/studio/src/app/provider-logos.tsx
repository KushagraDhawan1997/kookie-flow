interface ProviderLogoProps {
  /** The mark to draw; absent draws the maker's initial. */
  provider?: ProviderId;
  /** The maker's name: the accessible name when the mark stands alone. */
  maker: string;
  /** Whose initial stands in when there is no mark: the model's name, so "Open source" never shows an "O". */
  name: string;
  /** Decorative when the maker's name is written beside it. */
  decorative?: boolean;
}

export function ProviderLogo({ provider, maker, name, decorative = true }: ProviderLogoProps) {
  const a11y = decorative ? { 'aria-hidden': true as const } : { role: 'img', 'aria-label': maker };
  if (!provider) {
    return (
      <span className="kd-logo kd-logo-initial" {...a11y}>
        {name.charAt(0).toUpperCase()}
      </span>
    );
  }
  return (
    <svg className="kd-logo" viewBox="0 0 24 24" fill="currentColor" fillRule="evenodd" {...a11y}>
      {MARKS[provider].body}
    </svg>
  );
}
